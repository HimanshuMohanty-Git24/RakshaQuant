"""
The demo (plan M2.6, M5.6, M9.6): the real v2 engine replaying the **bundled fixture tape**
(``src/engine/demo_tape/``, one synthetic session on :data:`DEMO_DAY`), paced so the whole session
plays in a few minutes. Every price is ``MarketDataSource.SIMULATED``, which the RiskEngine allows
to trade only in the ``demo`` environment (its own ``var/demo/`` state).

The tape is generated by :func:`synthetic_day` (``scripts/build_demo_tape.py``); a test checks
the committed files still match it, so every demo run - and the M10 end-to-end tests - replay
exactly the same day: INFY's momentum signal runs to its target, TCS's to its stop.

No decision model runs in the demo, so the typed-veto book gets a :class:`ScriptedVeto` that
vetoes TCS (recorded as the model ``demo-script``, never as a real verdict): the paired books
then show a veto that avoided a loss, end to end.
"""

